// Exports Lockwatch ABIs from Foundry artifacts into the SDK.
import { readFileSync, writeFileSync } from "node:fs";
for (const [name, v] of [["LockwatchVault", "lockwatchVaultAbi"], ["LockwatchRescue", "lockwatchRescueAbi"]]) {
  const art = JSON.parse(readFileSync(`contracts/out/${name}.sol/${name}.json`, "utf8"));
  writeFileSync(
    `packages/sdk/src/abi/${name}.ts`,
    `// generated by scripts/export-abi.mjs — do not edit\nexport const ${v} = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
  );
  console.log("wrote", name, art.abi.length, "entries");
}
