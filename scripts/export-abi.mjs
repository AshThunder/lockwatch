// Exports LockwatchVault ABI from Foundry artifacts into the SDK.
import { readFileSync, writeFileSync } from "node:fs";
const art = JSON.parse(readFileSync("contracts/out/LockwatchVault.sol/LockwatchVault.json", "utf8"));
writeFileSync(
  "packages/sdk/src/abi/LockwatchVault.ts",
  `// generated by scripts/export-abi.mjs — do not edit\nexport const lockwatchVaultAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`,
);
console.log("wrote", art.abi.length, "entries");
